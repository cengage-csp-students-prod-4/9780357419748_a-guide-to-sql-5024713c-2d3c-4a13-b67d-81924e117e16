CREATE TABLE SUMMER_SCHOOL_RENTALS (
  PROPERTY_ID NUMERIC NOT NULL,
  OFFICE_NUM NUMERIC NOT NULL,
  ADDRESS VARCHAR(100) NOT NULL,
