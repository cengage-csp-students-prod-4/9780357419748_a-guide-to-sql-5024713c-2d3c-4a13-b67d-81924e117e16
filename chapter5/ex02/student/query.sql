SELECT 
    PROPERTY.ADDRESS,
    PROPERTY.SQR_FT,
    PROPERTY.OWNER_NUM,
    SERVICE_REQUEST.SERVICE_ID,
    SERVICE_REQUEST.EST_HOURS,
    SERVICE_REQUEST.SPENT_HOURS
FROM PROPERTY
LEFT JOIN SERVICE_REQUEST 
    ON PROPERTY.PROPERTY_ID = SERVICE_REQUEST.PROPERTY_ID
   AND SERVICE_REQUEST.CATEGORY_NUMBER = 4;