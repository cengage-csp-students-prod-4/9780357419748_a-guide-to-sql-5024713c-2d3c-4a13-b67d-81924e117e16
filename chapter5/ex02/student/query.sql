SELECT 
    PROPERTY.SQR_FT,
    PROPERTY.OWNER_NUM,
    OWNER.LAST_NAME,
    OWNER.FIRST_NAME
FROM PROPERTY, OWNER
WHERE PROPERTY.OWNER_NUM = OWNER.OWNER_NUM
  AND PROPERTY.OFFICE_NUM IN (
      SELECT OFFICE.OFFICE_NUM
      FROM OFFICE
      WHERE OFFICE.OFFICE_NAME = 'StayWell-Columbia City'
  );