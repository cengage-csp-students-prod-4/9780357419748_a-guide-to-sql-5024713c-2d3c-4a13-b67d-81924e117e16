SELECT 
    p.PROPERTY_ID,
    p.OFFICE_NUM,
    p.ADDRESS,
    sr.EST_HOURS,
    sr.SPENT_HOURS,
    o.OWNER_NUM,
    o.LAST_NAME
FROM SERVICE_REQUEST sr
JOIN SERVICE_CATEGORY sc 
    ON sr.CATEGORY_NUMBER = sc.CATEGORY_NUM
JOIN PROPERTY p 
    ON sr.PROPERTY_ID = p.PROPERTY_ID
JOIN OWNER o 
    ON p.OWNER_NUM = o.OWNER_NUM
WHERE sc.CATEGORY_DESCRIPTION = 'Janitorial' 
   OR sc.CATEGORY_DESCRIPTION = 'Janitorial Work';