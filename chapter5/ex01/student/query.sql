SELECT INVOICE_NUM, INVOICE_DATE
FROM INVOICES
WHERE CUST_ID IN (
    SELECT CUST_ID
    FROM CUSTOMER
    WHERE FIRST_NAME = 'James'
      AND LAST_NAME = 'Gonzalez'
)
EXCEPT
SELECT INVOICES.INVOICE_NUM, INVOICES.INVOICE_DATE
FROM INVOICES
JOIN INVOICE_LINE ON INVOICES.INVOICE_NUM = INVOICE_LINE.INVOICE_NUM
JOIN ITEM ON INVOICE_LINE.ITEM_ID = ITEM.ITEM_ID
WHERE ITEM.DESCRIPTION = 'Wild Bird Food (25 lb)';